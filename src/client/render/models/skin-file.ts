/**
 * The committed form of a baked skin (D-ART-008): a TypeScript module exporting the binary as base64, in lines, so
 * the game imports it synchronously and git diffs stay readable. Written by tests/anim/bake-skins.ts and read back by
 * skins.test.ts.
 */
const LINE = 120;

/** Base64 without Buffer (the client config has no Node types). */
function base64(bin: Uint8Array): string {
  let s = '';
  for (let i = 0; i < bin.length; i++) s += String.fromCharCode(bin[i] as number);
  return btoa(s);
}

/** The module text for a hero's baked skin. */
export function skinModule(id: string, bin: Uint8Array): string {
  const b64 = base64(bin);
  const lines: string[] = [];
  for (let i = 0; i < b64.length; i += LINE) lines.push(b64.slice(i, i + LINE));
  return `// Generated by tests/anim/bake-skins.ts from bodies.ts (D-ART-008): the ${id}'s implicit body, baked. Do not edit.\nexport const SKIN = \`\n${lines.join('\n')}\n\`;\n`;
}

/** The base64 back out of a module's text. */
export function skinOf(module: string): string {
  return (/`([^`]*)`/.exec(module)?.[1] ?? '').replace(/\s+/g, '');
}
