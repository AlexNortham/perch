// Bake the world's implicit bodies (D-ART-014): `npx tsx tests/anim/bake-world.ts [name…]`.
// For each body in src/client/render/models/world-bodies.ts (or those named), mesh its field and write
// src/client/render/models/data/world/<name>.ts. Deterministic: world-skins.test.ts re-bakes and compares.
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { WORLD_BODIES } from '../../src/client/render/models/world-bodies';
import type { WorldBody } from '../../src/client/render/models/world-bodies';
import { bakeBody } from '../../src/client/render/models/mesher';
import { skinModule } from '../../src/client/render/models/skin-file';

const DIR = resolve('src/client/render/models/data/world');
mkdirSync(DIR, { recursive: true });
const names = (process.argv.length > 2 ? process.argv.slice(2) : Object.keys(WORLD_BODIES)) as WorldBody[];
for (const name of names) {
  const t0 = performance.now();
  const bin = await bakeBody(WORLD_BODIES[name]());
  const text = skinModule(name, bin).replace(/^\/\/ .*\n/, `// Generated by tests/anim/bake-world.ts from world-bodies.ts (D-ART-014): the ${name}, baked. Do not edit.\n`);
  writeFileSync(`${DIR}/${name}.ts`, text);
  console.log(`bake-world: ${name} ${(bin.length / 1024).toFixed(0)} KB in ${((performance.now() - t0) / 1000).toFixed(1)} s`);
}
